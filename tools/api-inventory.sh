#!/usr/bin/env bash
# Regenerates docs/API_INVENTORY.md from compiled classes (javap -public).
# Usage: ./gradlew classes && tools/api-inventory.sh > docs/API_INVENTORY.md
set -euo pipefail
cd "$(dirname "$0")/.."
echo "# Public API inventory"
echo
echo "Generated by \`tools/api-inventory.sh\` from compiled classes (\`javap -public\`); do not edit by hand."
echo "Nested types appear as \`Outer\$Inner\`. Synthetic and private members are omitted by javap."
for m in bbnors-core bbnors-motion bbnors-engine bbnors-api bbnors-lab bbnors-examples; do
  dir="$m/build/classes/java/main"
  echo
  echo "## $m"
  echo
  echo "Source: \`$m/src/main/java\`"
  [ -d "$dir" ] || { echo; echo "_not compiled_"; continue; }
  classes=$(cd "$dir" && find . -name '*.class' | sed 's|^\./||; s|\.class$||; s|/|.|g' | sort)
  pkg=""
  for c in $classes; do
    out=$(javap -public -cp "$dir" "$c" 2>/dev/null | grep -v '^Compiled from' || true)
    [ -n "$out" ] || continue
    p="${c%.*}"
    if [ "$p" != "$pkg" ]; then pkg="$p"; echo; echo "### \`$pkg\`"; fi
    echo
    echo '```java'
    echo "$out" | sed "s/$pkg\.//g; s/java\.lang\.//g; s/java\.util\.function\.//g; s/java\.util\.//g; s/org\.bbnors\.[a-z.]*\.//g"
    echo '```'
  done
done
