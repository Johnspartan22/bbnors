#!/usr/bin/env bash
# Regenerates docs/COMMIT_HISTORY.md: every commit with full hash and the files it changed.
# Usage: tools/commit-history.sh > docs/COMMIT_HISTORY.md   (run after committing)
set -euo pipefail
cd "$(dirname "$0")/.."
echo "# Commit history"
echo
echo "Generated by \`tools/commit-history.sh\`. A commit that regenerates this file cannot list its own hash; see \`git log\` for the newest entry."
echo
echo "Status codes: A = added, M = modified, D = deleted, R = renamed."
for c in $(git log --format=%H --reverse); do
  echo
  echo "## \`$c\`"
  echo
  echo "**$(git log -1 --format=%s "$c")**  "
  echo "$(git log -1 --format='%ad' --date=iso "$c") · $(git show --stat --format='' "$c" | tail -1 | sed 's/^ *//')"
  echo
  echo '<details><summary>Files</summary>'
  echo
  echo '```'
  git show --name-status --format='' "$c"
  echo '```'
  echo
  echo '</details>'
done
